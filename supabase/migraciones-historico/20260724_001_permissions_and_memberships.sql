insert into public.project_members(project_id,user_id,is_active,assigned_by)
select project_id,p.id,p.is_active,null
from public.profiles p
cross join lateral unnest(coalesce(p.project_ids,array[]::text[])) as project_id
where project_id is not null and project_id<>''
on conflict (project_id,user_id) do update set is_active=excluded.is_active,updated_at=now();

-- 9) Funciones de autorización. service_role y SECURITY DEFINER son usados por
-- Edge Functions; el frontend nunca recibe la service_role.
create or replace function public.user_has_permission_for(p_user_id uuid,p_permission_code text)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select case
    when exists(select 1 from public.profiles p where p.id=p_user_id and p.is_active and p.role='IT') then true
    when exists(
      select 1
      from public.user_permission_overrides uo
      join public.permissions pe on pe.id=uo.permission_id
      where uo.user_id=p_user_id and pe.code=p_permission_code
    ) then coalesce((
      select uo.allowed
      from public.user_permission_overrides uo
      join public.permissions pe on pe.id=uo.permission_id
      where uo.user_id=p_user_id and pe.code=p_permission_code
      limit 1
    ),false)
    else coalesce((
      select rp.allowed
      from public.profiles p
      join public.role_permissions rp on rp.role=p.role
      join public.permissions pe on pe.id=rp.permission_id
      where p.id=p_user_id and p.is_active and pe.code=p_permission_code
      limit 1
    ),false)
  end;
$$;

create or replace function public.current_user_has_permission(p_permission_code text)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select public.user_has_permission_for(auth.uid(),p_permission_code);
$$;

revoke all on function public.user_has_permission_for(uuid,text) from public;
grant execute on function public.user_has_permission_for(uuid,text) to authenticated,service_role;
revoke all on function public.current_user_has_permission(text) from public;
grant execute on function public.current_user_has_permission(text) to authenticated;

-- 10) RLS de catálogos y asignaciones.
alter table public.permissions enable row level security;
alter table public.role_permissions enable row level security;
alter table public.user_permission_overrides enable row level security;
alter table public.project_members enable row level security;
alter table public.audit_logs enable row level security;
alter table public.login_directory enable row level security;

drop policy if exists permissions_read_authenticated on public.permissions;
create policy permissions_read_authenticated on public.permissions for select to authenticated using (true);

drop policy if exists role_permissions_read_authenticated on public.role_permissions;
create policy role_permissions_read_authenticated on public.role_permissions for select to authenticated using (true);

drop policy if exists overrides_read_authorized on public.user_permission_overrides;
create policy overrides_read_authorized on public.user_permission_overrides for select to authenticated
using (user_id=auth.uid() or public.current_user_has_permission('users.permissions.manage'));

drop policy if exists project_members_read_authorized on public.project_members;
create policy project_members_read_authorized on public.project_members for select to authenticated
using (user_id=auth.uid() or public.current_user_has_permission('users.view'));

drop policy if exists audit_read_authorized on public.audit_logs;
create policy audit_read_authorized on public.audit_logs for select to authenticated
using (public.current_user_has_permission('audit.view'));

drop policy if exists anon_read_login_directory on public.login_directory;
create policy anon_read_login_directory on public.login_directory for select to anon,authenticated using (is_active=true);

grant select on public.permissions,public.role_permissions,public.user_permission_overrides,public.project_members to authenticated;
grant select on public.audit_logs to authenticated;
grant select on public.login_directory to anon,authenticated;

