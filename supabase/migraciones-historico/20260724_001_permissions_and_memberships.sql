-- 7) Función auxiliar para asignar defaults de forma idempotente.
create or replace function public.qpc_set_role_permission(p_role text,p_code text,p_allowed boolean default true)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.role_permissions(role,permission_id,allowed)
  select p_role,id,p_allowed from public.permissions where code=p_code
  on conflict (role,permission_id) do update set allowed=excluded.allowed,updated_at=now();
end;
$$;

