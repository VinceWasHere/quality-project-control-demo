-- 2) Catálogo de permisos.
create table if not exists public.permissions (
  id bigint generated by default as identity primary key,
  code text not null unique,
  name text not null,
  description text not null default '',
  category text not null,
  sort_order integer not null default 0,
  created_at timestamptz not null default now()
);

create table if not exists public.role_permissions (
  role text not null,
  permission_id bigint not null references public.permissions(id) on delete cascade,
  allowed boolean not null default true,
  updated_at timestamptz not null default now(),
  primary key (role, permission_id),
  constraint role_permissions_role_check check (role in ('EJECUCION','CALIDAD','COORDINADOR_CALIDAD','GERENCIA','PRESIDENTE','IT'))
);

create table if not exists public.user_permission_overrides (
  user_id uuid not null references public.profiles(id) on delete cascade,
  permission_id bigint not null references public.permissions(id) on delete cascade,
  allowed boolean not null,
  granted_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  primary key (user_id, permission_id)
);

-- 3) Asignación relacional de proyectos. project_id es text durante la transición
-- porque la aplicación actual usa códigos como LCE/VC. La migración relacional
-- completa de proyectos se hará en la siguiente fase sin romper datos existentes.
create table if not exists public.project_members (
  project_id text not null,
  user_id uuid not null references public.profiles(id) on delete cascade,
  is_active boolean not null default true,
  assigned_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  primary key (project_id, user_id)
);

-- 4) Auditoría mínima para administración.
create table if not exists public.audit_logs (
  id bigint generated by default as identity primary key,
  project_id text,
  actor_id uuid references public.profiles(id) on delete set null,
  action text not null,
  entity_type text not null,
  entity_id text,
  previous_data jsonb,
  new_data jsonb,
  created_at timestamptz not null default now()
);

-- 5) Directorio limitado del login.
create table if not exists public.login_directory (
  email text primary key,
  full_name text not null,
  role text not null,
  is_active boolean not null default true,
  updated_at timestamptz not null default now()
);

