  select p_role,id,p_allowed from public.permissions where code=p_code
  on conflict (role,permission_id) do update set allowed=excluded.allowed,updated_at=now();
end;
$function$
;

CREATE OR REPLACE FUNCTION public.qpc_start_inspection_visit(p_actor uuid, p_inspection_id uuid, p_payload jsonb)
 RETURNS qpc_inspection_visits
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
  v_ins public.qpc_inspections; v_visit public.qpc_inspection_visits; v_type text=upper(coalesce(p_payload->>'visit_type','LIBERACION'));
  v_number integer; v_new_status text; v_old text; v_previous public.qpc_inspection_visits;
begin
  select * into v_ins from public.qpc_inspections where id=p_inspection_id for update;
  if v_ins.id is null then raise exception 'Inspección no encontrada'; end if;
  if not public.qpc_user_can_access_project(p_actor,v_ins.project_id) then raise exception 'No tiene acceso al proyecto'; end if;
  if v_type='LIBERACION' and not public.user_has_permission_for(p_actor,'inspections.evaluate') then raise exception 'No puede evaluar liberaciones'; end if;
  if v_type='SEGUIMIENTO' and not public.user_has_permission_for(p_actor,'inspections.start_follow_up') then raise exception 'No puede iniciar seguimientos'; end if;
  if v_type='CIERRE' and not public.user_has_permission_for(p_actor,'inspections.start_closure') then raise exception 'No puede iniciar cierres'; end if;
  if exists(select 1 from public.qpc_inspection_visits where inspection_id=p_inspection_id and status='EN_PROCESO') then raise exception 'Ya existe una visita en proceso'; end if;
  if v_ins.assigned_quality_id is null then update public.qpc_inspections set assigned_quality_id=p_actor where id=p_inspection_id; v_ins.assigned_quality_id=p_actor; end if;
  if v_ins.assigned_quality_id<>p_actor and not public.user_has_permission_for(p_actor,'inspections.edit_closed_visit') then raise exception 'La inspección está asignada a otro inspector'; end if;
  if v_type='LIBERACION' and exists(select 1 from public.qpc_inspection_visits where inspection_id=p_inspection_id and status='FINALIZADA') then raise exception 'La liberación inicial ya fue evaluada'; end if;
  if v_type in ('SEGUIMIENTO','CIERRE') and not exists(select 1 from public.qpc_inspection_visits where inspection_id=p_inspection_id and status='FINALIZADA') then raise exception 'Primero debe completarse la visita de liberación'; end if;
  select coalesce(max(visit_number),0)+1 into v_number from public.qpc_inspection_visits where inspection_id=p_inspection_id;
  select * into v_previous from public.qpc_inspection_visits where inspection_id=p_inspection_id and status='FINALIZADA' order by visit_number desc limit 1;
  v_new_status=case v_type when 'LIBERACION' then 'VISITA_LIBERACION_EN_PROCESO' when 'SEGUIMIENTO' then 'SEGUIMIENTO_EN_PROCESO' else 'CIERRE_EN_PROCESO' end;
  insert into public.qpc_inspection_visits(
    inspection_id,visit_number,visit_type,template_id,activity,stage,template_snapshot,answers_snapshot,notes_snapshot,
    started_by,status,objective
  ) values(
    p_inspection_id,v_number,v_type,p_payload->>'template_id',coalesce(p_payload->>'activity',v_ins.activity),
    coalesce(p_payload->>'stage',v_ins.stage),p_payload->'template_snapshot',
    case when coalesce((p_payload->>'copy_previous')::boolean,false) then coalesce(v_previous.answers_snapshot,'{}'::jsonb) else '{}'::jsonb end,
    case when coalesce((p_payload->>'copy_previous')::boolean,false) then coalesce(v_previous.notes_snapshot,'{}'::jsonb) else '{}'::jsonb end,
    p_actor,'EN_PROCESO',coalesce((p_payload->>'objective')::numeric,v_ins.objective)
  ) returning * into v_visit;
  v_old=v_ins.status;
  update public.qpc_inspections set status=v_new_status,template_id=v_visit.template_id,activity=v_visit.activity,stage=v_visit.stage where id=p_inspection_id;
  perform public.qpc_record_status(p_inspection_id,v_old,v_new_status,p_actor,'Visita '||v_number||' iniciada · '||v_type);
  insert into public.audit_logs(project_id,actor_id,action,entity_type,entity_id,new_data)
  values(v_ins.project_id,p_actor,'inspection.visit_started','inspection_visit',v_visit.id::text,to_jsonb(v_visit));
  return v_visit;
end; $function$
;

CREATE OR REPLACE FUNCTION public.qpc_sync_inspection_resources(p_inspection_id uuid)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
  v_ins public.qpc_inspections%rowtype;
  v_item jsonb;
  v_file uuid;
  v_index integer:=0;
  v_annotation jsonb;
  v_mapping_version uuid;
  v_annotation_id uuid;
  v_linked integer:=0;
begin
  select * into v_ins from public.qpc_inspections where id=p_inspection_id;
  if not found then return jsonb_build_object('ok',false,'message','Inspección no encontrada'); end if;

  for v_item in select value from jsonb_array_elements(coalesce(v_ins.attachments,'[]'::jsonb)) loop
    v_index=v_index+1;
    v_file=public.qpc_register_file_metadata(v_ins.project_id,v_item,v_ins.requested_by);
    if v_file is not null then
      insert into public.qpc_file_links(project_id,file_id,entity_type,entity_id,file_role,caption,sort_order,created_by)
      values(
        v_ins.project_id,v_file,'INSPECTION',v_ins.id,
        public.qpc_normalize_file_role(v_item->>'kind',coalesce(v_item->>'type',v_item->>'mime_type')),
        coalesce(v_item->>'kind','Adjunto'),v_index,v_ins.requested_by
      )
      on conflict (file_id,entity_type,entity_id,file_role) do update set
        caption=excluded.caption,sort_order=excluded.sort_order,deleted_at=null;
      v_linked=v_linked+1;
    elsif coalesce(v_item->>'dataUrl',v_item->>'data_url','')<>'' then
      insert into public.qpc_migration_issues(project_id,entity_type,entity_id,issue_code,detail,source_data,fingerprint)
      values(v_ins.project_id,'INSPECTION',v_ins.id::text,'LEGACY_BASE64_ATTACHMENT','Adjunto Base64 histórico pendiente de carga a Storage.',v_item,encode(extensions.digest(convert_to(v_ins.id::text||':attachment:'||v_index,'UTF8'),'sha256'),'hex'))
      on conflict (fingerprint) do nothing;
    end if;
  end loop;

  v_annotation=v_ins.mapping_annotation;
  if v_annotation is not null then
    if jsonb_typeof(v_annotation)='object' then
      v_file=public.qpc_register_file_metadata(v_ins.project_id,v_annotation,v_ins.requested_by);
      v_mapping_version=coalesce(
        case when coalesce(v_annotation->>'mappingVersionId','') ~* '^[0-9a-f]{8}-[0-9a-f]{4}-[1-5][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$' then (v_annotation->>'mappingVersionId')::uuid else null end,
        public.qpc_find_mapping_version(v_ins.mapping_id)
      );
      if v_file is not null and v_mapping_version is not null then
        insert into public.qpc_mapping_annotations(mapping_version_id,inspection_id,strokes,preview_file_id,created_by,title,opacity,tool_version,deleted_at)
        values(
          v_mapping_version,v_ins.id,coalesce(v_annotation->'strokes','[]'::jsonb),v_file,v_ins.requested_by,
          coalesce(nullif(v_annotation->>'title',''),'Mapeo marcado'),
          coalesce(nullif(v_annotation->>'opacity','')::numeric,0.180),
          coalesce(nullif(v_annotation->>'toolVersion',''),'QPC-HIGHLIGHTER-V2'),null
        )
        on conflict (inspection_id,mapping_version_id) where inspection_id is not null and deleted_at is null
        do update set strokes=excluded.strokes,preview_file_id=excluded.preview_file_id,title=excluded.title,opacity=excluded.opacity,tool_version=excluded.tool_version,updated_at=now()
        returning id into v_annotation_id;

        insert into public.qpc_file_links(project_id,file_id,entity_type,entity_id,file_role,caption,created_by)
        values(v_ins.project_id,v_file,'MAPPING_ANNOTATION',v_annotation_id,'MAPPING_ANNOTATION_PREVIEW','Mapeo marcado',v_ins.requested_by)
        on conflict (file_id,entity_type,entity_id,file_role) do update set deleted_at=null;
      end if;
    elsif jsonb_typeof(v_annotation)='string' and trim(both '"' from v_annotation::text) like 'data:image/%' then
      insert into public.qpc_migration_issues(project_id,entity_type,entity_id,issue_code,detail,source_data,fingerprint)
      values(v_ins.project_id,'INSPECTION',v_ins.id::text,'LEGACY_BASE64_MAPPING_ANNOTATION','Mapeo marcado histórico en Base64 pendiente de migración.',jsonb_build_object('length',length(v_annotation::text)),encode(extensions.digest(convert_to(v_ins.id::text||':mapping-annotation','UTF8'),'sha256'),'hex'))
      on conflict (fingerprint) do nothing;
    end if;
  end if;

  return jsonb_build_object('ok',true,'linked',v_linked,'annotation_id',v_annotation_id);
end;
$function$
;

