CREATE OR REPLACE FUNCTION public.qpc_set_personal_inspection_archive(p_inspection_id uuid, p_archived boolean, p_reason text DEFAULT ''::text)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
  v_actor uuid:=auth.uid();
  v_role text;
  v_active boolean;
  v_project_id text;
  v_status text;
  v_code text;
  v_assigned_quality uuid;
  v_now timestamptz:=now();
begin
  if v_actor is null then
    raise exception 'Sesión no válida.' using errcode='42501';
  end if;

  select role,is_active
    into v_role,v_active
  from public.profiles
  where id=v_actor;

  if coalesce(v_active,false)=false then
    raise exception 'El perfil no está activo.' using errcode='42501';
  end if;

  if v_role<>'IT' and not public.user_has_permission_for(v_actor,'inspections.archive') then
    raise exception 'No tiene permiso para archivar inspecciones.' using errcode='42501';
  end if;

  select project_id,status,request_code,assigned_quality_id
    into v_project_id,v_status,v_code,v_assigned_quality
  from public.qpc_inspections
  where id=p_inspection_id;

  if not found then
    raise exception 'La inspección no existe.' using errcode='P0002';
  end if;

  if not public.qpc_user_can_access_project(v_actor,v_project_id) then
    raise exception 'No tiene acceso al proyecto de esta inspección.' using errcode='42501';
  end if;

  -- El archivo personal de Calidad solo opera sobre su propia bandeja. IT puede
  -- organizar personalmente cualquier inspección a la que tenga acceso.
  if v_role<>'IT' and v_assigned_quality is distinct from v_actor then
    raise exception 'Solo puede archivar inspecciones asignadas a su usuario.' using errcode='42501';
  end if;

  if p_archived then
    if v_status not in ('LIBERADA','NO_LIBERADA','CERRADA','IMPROCEDENTE','ANULADA') then
      raise exception 'Solo se pueden archivar inspecciones terminadas o anuladas. Estado actual: %.',v_status using errcode='22023';
    end if;

    insert into public.qpc_inspection_user_archives(
      inspection_id,user_id,archived_at,archive_reason
    ) values (
      p_inspection_id,v_actor,v_now,left(coalesce(p_reason,''),500)
    )
    on conflict (inspection_id,user_id)
    do update set archived_at=excluded.archived_at,
                  archive_reason=excluded.archive_reason;
  else
    delete from public.qpc_inspection_user_archives
    where inspection_id=p_inspection_id and user_id=v_actor;
  end if;

  if to_regclass('public.audit_logs') is not null then
    insert into public.audit_logs(
      project_id,actor_id,action,entity_type,entity_id,previous_data,new_data,created_at
    ) values (
      v_project_id,
      v_actor,
      case when p_archived then 'inspection.personal_archive' else 'inspection.personal_restore' end,
      'inspection',
      p_inspection_id::text,
      jsonb_build_object('archived',not p_archived,'request_code',v_code),
      jsonb_build_object('archived',p_archived,'request_code',v_code,'reason',left(coalesce(p_reason,''),500)),
      v_now
    );
  end if;

  return jsonb_build_object(
    'ok',true,
    'inspection_id',p_inspection_id,
    'request_code',v_code,
    'archived',p_archived,
    'archived_at',case when p_archived then v_now else null end
  );
end;
$function$
;

CREATE OR REPLACE FUNCTION public.qpc_set_report_cycle_status(p_project_id text, p_period_mode text, p_period_value text, p_action text, p_notes text DEFAULT ''::text)
 RETURNS qpc_report_cycles
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
  v_actor uuid:=auth.uid();
  v_cycle public.qpc_report_cycles;
  v_previous text;
  v_new text;
  v_permission text;
  v_snapshot jsonb;
begin
  if v_actor is null then raise exception 'Sesión no válida.'; end if;
  if p_period_mode not in ('week','month') then raise exception 'Tipo de periodo no válido.'; end if;
  if coalesce(trim(p_period_value),'')='' then raise exception 'Periodo requerido.'; end if;

  v_permission:=case upper(p_action)
    when 'SAVE_DRAFT' then 'reports.review.manage'
    when 'MARK_READY' then 'reports.review.manage'
    when 'APPROVE' then 'reports.review.approve'
    when 'PUBLISH' then 'reports.review.publish'
    when 'REOPEN' then 'reports.review.manage'
    else null end;
  if v_permission is null then raise exception 'Acción no válida.'; end if;
  if not public.user_has_permission_for(v_actor,v_permission) then
    raise exception 'No tiene permiso para completar esta acción.';
  end if;

  select * into v_cycle
  from public.qpc_report_cycles
  where project_id=p_project_id and period_mode=p_period_mode and period_value=p_period_value
  for update;

  if not found then
    insert into public.qpc_report_cycles(project_id,period_mode,period_value,created_by,updated_by)
    values(p_project_id,p_period_mode,p_period_value,v_actor,v_actor)
    returning * into v_cycle;
  end if;

  v_previous:=v_cycle.status;
  v_new:=case upper(p_action)
    when 'SAVE_DRAFT' then 'DRAFT'
    when 'MARK_READY' then 'READY_FOR_REVIEW'
    when 'APPROVE' then 'APPROVED'
    when 'PUBLISH' then 'PUBLISHED'
    when 'REOPEN' then 'DRAFT'
  end;

  if upper(p_action)='APPROVE' and v_previous<>'READY_FOR_REVIEW' then
    raise exception 'Solo se puede aprobar un informe listo para revisión.';
  end if;
  if upper(p_action)='PUBLISH' and v_previous<>'APPROVED' then
    raise exception 'Solo se puede publicar un informe aprobado.';
  end if;
  if upper(p_action)='MARK_READY' and v_previous not in ('DRAFT','READY_FOR_REVIEW') then
    raise exception 'Reabra el informe antes de marcarlo para revisión.';
  end if;

  select jsonb_build_object(
    'entries',count(*),
    'sections',count(distinct section_code),
    'generated_at',now()
  ) into v_snapshot
  from public.qpc_report_entries
  where project_id=p_project_id
    and period_mode=p_period_mode
    and period_value=p_period_value
    and coalesce(is_archived,false)=false;

  update public.qpc_report_cycles
  set status=v_new,
      review_notes=coalesce(p_notes,''),
      snapshot=coalesce(v_snapshot,'{}'::jsonb),
      updated_by=v_actor,
      updated_at=now(),
      revision_number=case when upper(p_action)='PUBLISH' then revision_number+1 else revision_number end,
      approved_by=case when upper(p_action)='APPROVE' then v_actor when upper(p_action)='REOPEN' then null else approved_by end,
      approved_at=case when upper(p_action)='APPROVE' then now() when upper(p_action)='REOPEN' then null else approved_at end,
      published_by=case when upper(p_action)='PUBLISH' then v_actor when upper(p_action)='REOPEN' then null else published_by end,
      published_at=case when upper(p_action)='PUBLISH' then now() when upper(p_action)='REOPEN' then null else published_at end
  where id=v_cycle.id
  returning * into v_cycle;

  insert into public.qpc_report_cycle_events(
    cycle_id,project_id,action,previous_status,new_status,revision_number,notes,actor_id
  ) values(
    v_cycle.id,p_project_id,upper(p_action),v_previous,v_new,v_cycle.revision_number,coalesce(p_notes,''),v_actor
  );

  insert into public.audit_logs(project_id,actor_id,action,entity_type,entity_id,previous_data,new_data,created_at)
  values(
    p_project_id,v_actor,'REPORT_'||upper(p_action),'REPORT_CYCLE',v_cycle.id::text,
    jsonb_build_object('status',v_previous),
    jsonb_build_object('status',v_new,'revision',v_cycle.revision_number),now()
  );

  return v_cycle;
end;
$function$
;

CREATE OR REPLACE FUNCTION public.qpc_set_report_section_check(p_project_id text, p_period_mode text, p_period_value text, p_section_code text, p_status text, p_notes text DEFAULT ''::text)
 RETURNS boolean
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
  v_actor uuid:=auth.uid();
  v_entry_count integer;
begin
  if v_actor is null then raise exception 'Sesión no válida.'; end if;
  if not public.user_has_permission_for(v_actor,'reports.validation.manage') then
    raise exception 'No tiene permiso para actualizar la validación.';
  end if;
  if not public.qpc_user_can_access_project(v_actor,p_project_id) then
    raise exception 'No tiene acceso al proyecto.';
  end if;
  if upper(p_status) not in ('PENDING','COMPLETE','NOT_APPLICABLE') then
    raise exception 'Estado de validación no válido.';
  end if;
  if not exists(select 1 from public.qpc_report_validation_catalog(p_period_mode) c where c.section_code=upper(p_section_code)) then
    raise exception 'Sección no válida para este tipo de informe.';
  end if;

  select count(*)::integer into v_entry_count
  from public.qpc_report_entries e
  where e.project_id=p_project_id
    and e.period_mode=p_period_mode
    and e.period_value=p_period_value
    and e.section_code=upper(p_section_code)
    and e.is_active=true
    and e.archived_at is null;

  if upper(p_status)='COMPLETE' and v_entry_count=0 then
    raise exception 'La sección no contiene registros. Utilice No aplica o agregue contenido.';
  end if;

  insert into public.qpc_report_section_checks(
    project_id,period_mode,period_value,section_code,review_status,notes,reviewed_by,reviewed_at,updated_at
  ) values(
    p_project_id,p_period_mode,p_period_value,upper(p_section_code),upper(p_status),coalesce(p_notes,''),
    case when upper(p_status)='PENDING' then null else v_actor end,
    case when upper(p_status)='PENDING' then null else now() end,
    now()
  )
  on conflict(project_id,period_mode,period_value,section_code) do update set
    review_status=excluded.review_status,
    notes=excluded.notes,
    reviewed_by=excluded.reviewed_by,
    reviewed_at=excluded.reviewed_at,
    updated_at=now();

  insert into public.audit_logs(project_id,actor_id,action,entity_type,entity_id,new_data,created_at)
  values(
    p_project_id,v_actor,'REPORT_VALIDATION_'||upper(p_status),'REPORT_SECTION',
    p_period_mode||':'||p_period_value||':'||upper(p_section_code),
    jsonb_build_object('period_mode',p_period_mode,'period_value',p_period_value,'section_code',upper(p_section_code),'status',upper(p_status),'notes',coalesce(p_notes,'')),
    now()
  );
  return true;
end;
$function$
;

