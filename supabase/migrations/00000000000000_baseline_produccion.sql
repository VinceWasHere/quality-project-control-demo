CREATE OR REPLACE FUNCTION public.qpc_build_report_snapshot(p_project_id text, p_period_mode text, p_period_value text)
 RETURNS jsonb
 LANGUAGE sql
 STABLE SECURITY DEFINER
 SET search_path TO 'public'
