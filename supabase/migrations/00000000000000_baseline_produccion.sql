create or replace view public.qpc_visit_deductions as
 SELECT a.visit_id,
    v.inspection_id,
    a.criterion_id,
    a.criterion_id AS criterion_code,
    COALESCE(c.name, a.criterion_name, 'Criterio'::text) AS criterion_name,
    COALESCE(a.criterion_stage, v.stage, 'General'::text) AS stage_name,
    a.is_visit_criterion,
    a.selected_label AS response_label,
    a.weight AS criterion_weight,
    a.points_earned,
    COALESCE(a.points_lost, GREATEST(COALESCE(a.weight, 0::numeric) - COALESCE(a.points_earned, 0::numeric), 0::numeric)) AS points_lost,
    a.observation AS comment,
    a.sort_order
   FROM qpc_visit_answers a
     JOIN qpc_inspection_visits v ON v.id = a.visit_id
     LEFT JOIN qpc_template_criteria c ON c.template_id = v.template_id AND c.criterion_id = a.criterion_id
  WHERE COALESCE(a.is_na, false) = false AND COALESCE(a.points_lost, GREATEST(COALESCE(a.weight, 0::numeric) - COALESCE(a.points_earned, 0::numeric), 0::numeric)) > 0::numeric;


