CREATE OR REPLACE FUNCTION public.qpc_refresh_due_equipment_notifications()
 RETURNS integer
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
  v_project record;
  v_profile record;
  v_items jsonb;
  v_expired integer;
  v_upcoming integer;
  v_body text;
  v_fingerprint text;
  v_event_key text;
  v_result uuid;
  v_count integer := 0;
begin
  if auth.uid() is null then
    raise exception 'Sesión requerida';
  end if;

  -- Retira cualquier alerta individual que todavía haya quedado activa.
  update public.qpc_notifications
  set archived_at = coalesce(archived_at, now()),
      read_at = coalesce(read_at, now())
  where category = 'EQUIPMENT'
    and archived_at is null
    and event_key like 'equipment:%:due:%';

  -- Se archivan temporalmente los resúmenes anteriores. Los proyectos que aún
  -- tienen equipos vencidos o próximos se reactivan mediante el UPSERT inferior.
  update public.qpc_notifications
  set archived_at = coalesce(archived_at, now())
  where category = 'EQUIPMENT'
    and event_key like 'equipment-summary:%';

  for v_project in
    select p.id, p.name
    from public.qpc_projects p
    where p.is_active = true
    order by p.name
  loop
    select
      coalesce(
        jsonb_agg(
          jsonb_build_object(
            'id', due.id,
            'code', due.equipment_code,
            'type', due.equipment_type,
            'brand_model', due.brand_model,
            'location', due.location_text,
            'responsible', due.responsible,
            'due_date', due.due_date,
            'status', due.status
          )
          order by due.due_date, due.equipment_code
        ),
        '[]'::jsonb
      ),
      (count(*) filter (where due.status = 'VENCIDO'))::integer,
      (count(*) filter (where due.status = 'PRÓXIMO'))::integer
    into v_items, v_expired, v_upcoming
    from (
      select
        e.id,
        e.equipment_code,
        e.equipment_type,
        e.brand_model,
        e.location_text,
        e.responsible,
        least(
          case
            when e.calibration_required and e.last_calibration_date is not null
              then e.last_calibration_date + e.frequency_days
          end,
          case
            when e.verification_required and e.last_verification_date is not null
              then e.last_verification_date + e.frequency_days
          end
        ) as due_date,
        case
          when least(
            case
              when e.calibration_required and e.last_calibration_date is not null
                then e.last_calibration_date + e.frequency_days
            end,
            case
              when e.verification_required and e.last_verification_date is not null
                then e.last_verification_date + e.frequency_days
            end
          ) < current_date then 'VENCIDO'
          else 'PRÓXIMO'
        end as status
      from public.qpc_equipment e
      where e.project_id = v_project.id
        and e.is_active = true
    ) due
    where due.due_date is not null
      and due.due_date <= current_date + 30;

    if jsonb_array_length(v_items) = 0 then
      continue;
    end if;

    v_body := concat_ws(
      ' · ',
      case when v_expired > 0 then v_expired || case when v_expired = 1 then ' vencido' else ' vencidos' end end,
      case when v_upcoming > 0 then v_upcoming || case when v_upcoming = 1 then ' próximo a vencer' else ' próximos a vencer' end end
    );
    v_fingerprint := md5(v_items::text);

    for v_profile in
      select distinct p.id
      from public.profiles p
      join public.project_members pm
        on pm.user_id = p.id
       and pm.project_id = v_project.id
       and pm.is_active = true
      where p.is_active = true
        and p.role in ('CALIDAD','COORDINADOR_CALIDAD','IT')
    loop
      v_event_key := concat('equipment-summary:', v_project.id, ':', v_profile.id);

      insert into public.qpc_notifications(
        recipient_id,
        project_id,
        category,
        title,
        body,
        entity_type,
        entity_id,
        action_view,
        event_key,
        metadata,
        created_at,
        archived_at
      ) values (
        v_profile.id,
        v_project.id,
        'EQUIPMENT',
        'Alertas de equipos',
        v_body,
        'EQUIPMENT_SUMMARY',
        v_project.id,
        'equipment',
        v_event_key,
        jsonb_build_object(
          'project_name', v_project.name,
          'expired_count', v_expired,
          'upcoming_count', v_upcoming,
          'total_count', v_expired + v_upcoming,
          'fingerprint', v_fingerprint,
          'items', v_items
        ),
        now(),
        null
      )
      on conflict (event_key) do update
      set title = excluded.title,
          body = excluded.body,
          metadata = excluded.metadata,
          entity_type = excluded.entity_type,
          entity_id = excluded.entity_id,
          action_view = excluded.action_view,
          archived_at = null,
          created_at = case
            when public.qpc_notifications.metadata->>'fingerprint'
                 is distinct from excluded.metadata->>'fingerprint'
              then now()
            else public.qpc_notifications.created_at
          end,
          read_at = case
            when public.qpc_notifications.metadata->>'fingerprint'
                 is distinct from excluded.metadata->>'fingerprint'
              then null
            else public.qpc_notifications.read_at
          end
      returning id into v_result;

      if v_result is not null then
        v_count := v_count + 1;
      end if;
    end loop;
  end loop;

  return v_count;
end;
$function$
;

CREATE OR REPLACE FUNCTION public.qpc_register_file_metadata(p_project_id text, p_metadata jsonb, p_uploaded_by uuid)
 RETURNS uuid
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
  v_bucket text;
  v_path text;
  v_url text;
  v_name text;
  v_type text;
  v_size bigint;
  v_id uuid;
begin
  v_bucket=coalesce(nullif(p_metadata->>'bucket',''),'qpc-attachments');
  v_path=coalesce(nullif(p_metadata->>'storagePath',''),nullif(p_metadata->>'storage_path',''));
  v_url=coalesce(nullif(p_metadata->>'externalUrl',''),nullif(p_metadata->>'external_url',''));
  v_name=coalesce(nullif(p_metadata->>'name',''),nullif(p_metadata->>'original_name',''),'archivo');
  v_type=coalesce(nullif(p_metadata->>'type',''),nullif(p_metadata->>'mime_type',''),'application/octet-stream');
  begin v_size=nullif(coalesce(p_metadata->>'size',p_metadata->>'size_bytes'),'')::bigint; exception when others then v_size=null; end;

  if v_path is null and v_url is null then return null; end if;
  if v_path is null and v_url is not null then
    select id into v_id from public.qpc_files where external_url=v_url limit 1;
    if v_id is not null then return v_id; end if;
  end if;

  insert into public.qpc_files(project_id,bucket,storage_path,external_url,original_name,mime_type,size_bytes,uploaded_by)
  values(p_project_id,v_bucket,v_path,v_url,v_name,v_type,v_size,p_uploaded_by)
  on conflict (bucket,storage_path) do update set
    project_id=coalesce(public.qpc_files.project_id,excluded.project_id),
    original_name=excluded.original_name,
    mime_type=excluded.mime_type,
    size_bytes=coalesce(excluded.size_bytes,public.qpc_files.size_bytes),
    deleted_at=null
  returning id into v_id;

  if v_id is null and v_url is not null then
    select id into v_id from public.qpc_files where external_url=v_url limit 1;
  end if;
  return v_id;
end;
$function$
;

CREATE OR REPLACE FUNCTION public.qpc_reorder_report_entry_files(p_entry_id uuid, p_link_ids uuid[])
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
  v_actor uuid:=auth.uid();
  v_entry public.qpc_report_entries%rowtype;
  v_expected integer;
  v_received integer;
begin
  if v_actor is null then raise exception 'Sesión no válida'; end if;
  select * into v_entry from public.qpc_report_entries where id=p_entry_id;
  if not found then raise exception 'Registro no encontrado'; end if;
  if not public.qpc_user_can_access_project(v_actor,v_entry.project_id) then raise exception 'No tiene acceso al proyecto'; end if;
  if not public.user_has_permission_for(v_actor,'reports.content.evidence.manage') then raise exception 'No tiene permiso para ordenar evidencias'; end if;

  select count(*) into v_expected from public.qpc_report_entry_files where entry_id=p_entry_id and archived_at is null;
  select count(distinct x) into v_received from unnest(coalesce(p_link_ids,array[]::uuid[])) x;
  if v_expected<>v_received then raise exception 'La lista de evidencias está incompleta'; end if;
  if exists(
    select 1 from unnest(p_link_ids) x
    where not exists(select 1 from public.qpc_report_entry_files l where l.id=x and l.entry_id=p_entry_id and l.archived_at is null)
  ) then raise exception 'La lista contiene una evidencia inválida'; end if;

  update public.qpc_report_entry_files l
  set sort_order=u.ord*10,updated_at=now()
  from unnest(p_link_ids) with ordinality u(id,ord)
  where l.id=u.id;

  insert into public.audit_logs(project_id,actor_id,action,entity_type,entity_id,new_data)
  values(v_entry.project_id,v_actor,'report_content.evidence_reordered','report_entry',p_entry_id::text,to_jsonb(p_link_ids));
end;
$function$
;

